// Vendors Web Platform Tests files into `tests/wpt/vendor/`.
// Usage (from apps/test-suite): node scripts/vendor-wpt.mjs
//
// Each file is wrapped as `export default function run() { ... }`, because Metro caches modules
// and a top-level script would register its tests only on the first run. The body stays verbatim.
// `// META: script=` support files are vendored too and listed in `vendor/index.js`, which the
// suite module requires statically.
import fs from 'node:fs';
import path from 'node:path';

const WPT_COMMIT = 'b0912c91005c07733ba19a2d93c712e8547df31a';

// Every `.any.js` file of `FileAPI/blob` and `FileAPI/file` that runs without the WPT server.
const FILES = [
  'FileAPI/blob/Blob-array-buffer.any.js',
  'FileAPI/blob/Blob-bytes.any.js',
  'FileAPI/blob/Blob-constructor-detached-buffer.any.js',
  'FileAPI/blob/Blob-constructor-endings.any.js',
  'FileAPI/blob/Blob-constructor.any.js',
  'FileAPI/blob/Blob-newobject.any.js',
  'FileAPI/blob/Blob-slice-overflow.any.js',
  'FileAPI/blob/Blob-slice.any.js',
  'FileAPI/blob/Blob-stream.any.js',
  'FileAPI/blob/Blob-text.any.js',
  'FileAPI/blob/Blob-textStream.any.js',
  'FileAPI/file/File-constructor-endings.any.js',
  'FileAPI/file/File-constructor.any.js',
];

// Not vendored, with the reason. Listed in the vendored README.
const SKIPPED = [
  ['FileAPI/*/*.html', 'need a DOM document or the WPT server'],
  ['FileAPI/blob/Blob-constructor-dom.window.js', 'needs DOM elements'],
  ['FileAPI/blob/Blob-in-worker.worker.js', 'needs a dedicated worker'],
  ['FileAPI/file/Worker-read-file-constructor.worker.js', 'needs a dedicated worker'],
  ['FileAPI/file/send-file-formdata*.any.js', 'need the WPT echo server'],
];

const vendorDir = path.join(import.meta.dirname, '../tests/wpt/vendor');

async function download(file) {
  const url = `https://raw.githubusercontent.com/web-platform-tests/wpt/${WPT_COMMIT}/${file}`;
  const response = await fetch(url);
  if (!response.ok) {
    throw new Error(`${url}: HTTP ${response.status}`);
  }
  return response.text();
}

// `../support/Blob.js` is relative to the test file, `/common/gc.js` to the WPT root.
function metaScripts(file, source) {
  return [...source.matchAll(/^\/\/ META: script=(.+)$/gm)].map(([, script]) =>
    script.startsWith('/') ? script.slice(1) : path.posix.join(path.posix.dirname(file), script)
  );
}

function writeWrapped(file, source) {
  const header =
    `// Vendored from web-platform-tests ${file} at ${WPT_COMMIT}\n` +
    `// by scripts/vendor-wpt.mjs. BSD-3-Clause, see LICENSE-wpt.md. Do not edit.\n`;
  const target = path.join(vendorDir, file);
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, `${header}export default function run() {\n${source}\n}\n`);
}

fs.rmSync(vendorDir, { recursive: true, force: true });
const written = new Set();
const manifest = [];
for (const file of FILES) {
  const source = await download(file);
  const scripts = metaScripts(file, source);
  for (const script of scripts) {
    if (!written.has(script)) {
      writeWrapped(script, await download(script));
      written.add(script);
    }
  }
  writeWrapped(file, source);
  manifest.push(
    `  {\n    path: '${file}',\n` +
      `    scripts: [${scripts.map((s) => `require('./${s}').default`).join(', ')}],\n` +
      `    run: require('./${file}').default,\n  },\n`
  );
}

fs.writeFileSync(
  path.join(vendorDir, 'index.js'),
  `// Generated by scripts/vendor-wpt.mjs. Do not edit.\nexport default [\n${manifest.join('')}];\n`
);
fs.writeFileSync(path.join(vendorDir, 'WPT_COMMIT'), `${WPT_COMMIT}\n`);
fs.writeFileSync(
  path.join(vendorDir, 'README.md'),
  `# Vendored Web Platform Tests\n\n` +
    `Generated by \`scripts/vendor-wpt.mjs\` from https://github.com/web-platform-tests/wpt at the\n` +
    `commit in \`WPT_COMMIT\`. Do not edit these files; rerun the script instead. Each file keeps its\n` +
    `upstream body inside an \`export default function run()\` wrapper.\n\n` +
    `Skipped upstream files:\n\n` +
    SKIPPED.map(([file, reason]) => `- \`${file}\`: ${reason}\n`).join('') +
    `\n` +
    `The files are licensed under the 3-Clause BSD License, see\n` +
    `[\`LICENSE-wpt.md\`](../../../LICENSE-wpt.md). The harness and the scoreboard are in\n` +
    `[\`../README.md\`](../README.md).\n`
);
console.log(`Vendored ${FILES.length} files and ${written.size} support files at ${WPT_COMMIT}`);
